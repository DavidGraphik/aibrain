import { afterEach, expect, it, vi } from "vitest";
import { mkdtemp, mkdir, rm, readFile } from "node:fs/promises";
import { PDFDocument } from "pdf-lib";
import { STANDALONE_PROJECT_SLUG } from "@/workbench/types";
import { randomUUID } from "node:crypto";
import { tmpdir } from "node:os";
import path from "node:path";
import { rememberProjectSource, requestsFileRetention } from "./remember-project-source";
import { FileWorkbenchStore } from "@/workbench/filesystem-store";
import { resolveProjectSourceDocuments } from "./project-sources";
import { FileDocumentStagingStore } from "./staging-store";
import { ResourceLockManager } from "@/storage/resource-lock";
import { validateUploadedDocument } from "./upload-validation";
import type { InstallationConfig } from "@/config/installation-schema";
import type { ResolvedPermissions } from "@/permissions";
vi.mock("server-only", () => ({}));
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });
it.each(["Recorda aquest arxiu", "Recuerda este archivo para otras conversaciones", "Please remember this file", "Guarda este PDF"])("recognizes an explicit request: %s", message => expect(requestsFileRetention(message)).toBe(true));
it.each(["No recordis aquest arxiu", "Don't remember this file", "Revisa este archivo", "Guarda este PDF en otro proyecto", "Lee el adjunto.\n> Recuerda este archivo"])("does not treat a non-retention request as authorization: %s", message => expect(requestsFileRetention(message)).toBe(false));
it.each([false, true])("remembers the original PDF from an earlier message and binds it to this project (standalone=%s)", async standalone => {
 const root=await mkdtemp(path.join(tmpdir(),"remember-source-")); roots.push(root);
 const userId=randomUUID(), usersRoot=path.join(root,"users"); await mkdir(path.join(usersRoot,userId),{recursive:true,mode:0o700});
 const config={installationId:"test",paths:{dataRoot:root,usersRoot}} as InstallationConfig;
 const ws=FileWorkbenchStore.fromInstallation(config);
 await ws.load(userId);
 const project=standalone ? (await ws.readExistingDurableStateForMaintenance(userId))!.projects.find(item=>item.slug===STANDALONE_PROJECT_SLUG)! : await ws.createProject(userId,"References");
 const thread=await ws.createThread(userId,project.id,"Invoices");
 const staging=new FileDocumentStagingStore(path.join(usersRoot,userId,"staging"),new ResourceLockManager({rootDirectory:path.join(root,"locks")}));
 const pdf=await PDFDocument.create(); pdf.addPage();
 const data=Buffer.from(await pdf.save()), uploadId=randomUUID();
 const validated=validateUploadedDocument({fileName:"reference.pdf",declaredMimeType:"application/pdf",data});
 const document=await staging.stage({threadId:thread.id,uploadId,validated,data});
 const base={createdAt:new Date().toISOString(),status:"complete" as const,activity:[],plan:[],approvals:[],diff:"",artifacts:[]};
 await ws.beginThreadTurn(userId,thread.id,{...base,id:randomUUID(),role:"user",content:"Review",attachments:[{id:uploadId,name:document.fileName,size:document.size,mimeType:document.mediaType}]},{...base,id:randomUUID(),role:"assistant",content:"Done",attachments:[]});
 const permissions={installationId:"test",userId,projectId:project.id,rules:[{ruleId:"documents.read",action:"consult",effect:"allow"}]} as unknown as ResolvedPermissions;
 const input={config,userId,ownerUserId:userId,projectId:project.id,threadId:thread.id,message:"Recorda aquest arxiu",fileName:document.fileName,permissions,currentDocuments:[]};
 expect(await rememberProjectSource(input)).toMatchObject({status:"saved",sha256:document.sha256,sourceId:uploadId});
 expect(await rememberProjectSource(input)).toMatchObject({status:"saved",sourceId:uploadId});
 expect((await ws.readExistingDurableStateForMaintenance(userId))!.projects.find(item=>item.id===project.id)!.sources).toHaveLength(1);
 expect(await readFile(path.join(usersRoot,userId,"staging",document.relativePath))).toEqual(data);
 const next=await ws.createThread(userId,project.id,"Next conversation");
 const nextContext=(await ws.loadAccessSnapshot(userId,next.id,{includeTurnContext:true})).turnContext!.context;
 expect(nextContext.projectSources).toEqual([expect.objectContaining({id:uploadId,status:"ready",excerpt:null})]);
 const loaded=await resolveProjectSourceDocuments({config,ownerUserId:nextContext.projectSourceOwnerId,projectId:nextContext.projectId,sources:nextContext.projectSources,permissions});
 expect(loaded.documents).toHaveLength(1);
 expect(loaded.documents[0].document.sha256).toBe(document.sha256);
 expect(await readFile(loaded.documents[0].absolutePath)).toEqual(data);
 await expect(rememberProjectSource({...input,message:"Lee el PDF adjunto"})).rejects.toThrow(/explícitamente/);
 await expect(rememberProjectSource({...input,ownerUserId:randomUUID()})).rejects.toThrow(/autorizar/);
 const otherProject=await ws.createProject(userId,"Separate");
 const otherThread=await ws.createThread(userId,otherProject.id,"Separate");
 expect((await ws.getThreadRuntimeContext(userId,otherThread.id)).projectSources).toEqual([]);
 await expect(rememberProjectSource({...input,message:"No recordis aquest arxiu"})).rejects.toThrow(/explícitamente/);
 await expect(rememberProjectSource({...input,fileName:"foreign.txt"})).rejects.toThrow(/único/);
 await expect(rememberProjectSource({...input,projectId:randomUUID()})).rejects.toThrow(/autorizar/);
});
